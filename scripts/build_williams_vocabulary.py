def material():
 assert hashlib.sha256(CANON.read_bytes()).hexdigest()=='582cb86ac4ac83dd600e7e5512c3c7d5d1d61d1e6f074296d3654e0c007e06d3','canonical source changed: review before regeneration'
 text=CANON.read_text(encoding='utf-8');manifest=json.loads((CANON.parent/'TECHNICAL_INVENTORY.json').read_text(encoding='utf-8'));by={x['id']:x for x in manifest['inventory']};cells=[]
 for number in R:
  x=by[f'JW-R{number:02}'];body=re.search(r'^#### '+x['id']+r' · .*?\n(.*?)(?=^###|\Z)',text,re.M|re.S)[1]
  grid=re.search(r'```(.*?)```',body,re.S)[1];patterns={role:pat.replace('|','') for role,pat in re.findall(r'^([A-Z]{2})\s+([Xx.\-|]+)',grid,re.M)}
  # Explicit constructed short-harmony variant of R03's movement carrier.
  pad=patterns.get('KF',patterns.get('AR','') if number==3 else '');bass=patterns.get('KB','')
  assert x['meter']=='4/4' and all(len(p)==32 and set(p)<=set('Xx.-') for p in (pad,bass) if p)
  # Every supplied detached gate must fit its destination; never auto-remap to long.
  for pat,limit in ((pad,3),(bass,4)):
   for i,ch in enumerate(pat):
    if ch in 'Xx':
     n=1
     while i+n<len(pat) and pat[i+n]=='-':n+=1
     assert n<=limit,(number,n,limit)
  if number==3:bass=re.search(r'^Bass\s+([Xx.\-|]+)',by['JW-B18']['grid'],re.M)[1].replace('|','')
  intervals=[0,7,12] if number==3 else [0,7] if number in (24,42) else [0]
  cells.append(dict(id=number,bass_id=18 if number==3 else 4 if number in (24,42) else 0,xyz=x['xyz'],pad=pad,bass=bass,intervals=intervals,pedal=False))
 # Explicit long-bass B01, no hidden detached->sustained routing.
 x=by['JW-B01'];cells.append(dict(id=0,bass_id=1,xyz=x['xyz'],pad='',bass='X'+'-'*31,intervals=[0],pedal=True))
 return by,cells

def main():
 p=argparse.ArgumentParser();mode=p.add_mutually_exclusive_group();mode.add_argument('--check',action='store_true');mode.add_argument('--import-harmony',action='store_true');args=p.parse_args();by,cells=material()
