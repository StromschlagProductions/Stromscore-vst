 for c in cells:
  h+='{'+f'{c["id"]},{c["bass_id"]},'+','.join(str(v)+'f' for v in c['xyz'])+','+json.dumps(c['pad'])+','+json.dumps(c['bass'])+','+'{'+','.join(map(str,c['intervals']))+'},'+str(len(c['intervals']))+','+str(c['pedal']).lower()+'},\n'
 h+='};\n}\n';path=ROOT/'Source/WilliamsVocabulary.generated.h'
 if args.check:
  assert path.read_text(encoding='utf-8')==h,'Williams rhythm data drift'
  cat=json.loads((ROOT/'data/harmony/catalog.json').read_text(encoding='utf-8'));templates={t['id']:t for t in cat['templates']}
  for number in H:
   x=by[f'JW-H{number:02}'];t=templates[40000+number]
