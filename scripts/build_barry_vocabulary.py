#!/usr/bin/env python3
"""Offline, canonical Barry R/M studies. No archive import or runtime file access."""
import argparse,json,pathlib,re,sys
ROOT=pathlib.Path(__file__).resolve().parents[1]
SOURCE='docs/research/shared/Musikalisches_Vokabular_Gesamtfassung_2026-11-24.txt'
R={1:('bass',),2:('bass',),3:('movement',),4:('movement',),5:('bass','movement'),8:('bass','movement'),10:('bass',),11:('bass',),13:('movement',),14:('movement',),17:('bass',),18:('movement',),20:('movement',),22:('bass',),24:('bass',),26:('bass','movement')}
DEFER={6:'A-A-B form planning',7:'Whole-texture silence, not only one muted part',9:'Tuned percussion plus chordal role not identified by MIDI patches',12:'Held pad exists; exact two-bar retrigger/envelope not imported',15:'Dense hypothetical motor deferred for underscoring',19:'Whole-texture eight-stage density procedure',21:'Pad/reinstrumentation role, not an Arp substitute',25:'Dense hypothetical motor deferred for underscoring',27:'Accent-role plan outside this two-part step'}
def read():
 text=(ROOT/SOURCE).read_text(encoding="utf-8");rhythms=[];motifs=[]
 for m in re.finditer(r'^#### (JB-([RM])(\d+)) · ([^\n]+)\n(.*?)(?=^#### |^## |^### |\Z)',text,re.M|re.S):
  ref,kind,num,name,body=m.groups();num=int(num)
  xyztext=re.search(r'\*\*XYZ:\*\* (.*?) →',body)[1]
  if kind=='R' and num in (3,12,15,21):
   xyztext=re.search(re.escape(ref)+r' \(Barry, XYZ ([^)]+)\)',body)[1]
  xyz=[float(x.strip().replace(',','.')) for x in xyztext.split('/')]
  assert len(xyz)==3 and all(0<=x<=1 for x in xyz)
  meter=re.search(r'(\d+)/(\d+)',body);meter=[int(meter[1]),int(meter[2])]
  evidence=re.search(r'Verfahren \[([NIH])\]',body)[1]
  row=dict(id=ref,name=name,xyz=xyz,meter=meter,evidence=evidence,construction='E',source=SOURCE)
  if kind=='R':
   rows=re.search(r'```\n(.*?)\n```',body,re.S)[1].splitlines();patterns=[line.split()[-1].split('|') for line in rows]
   length=meter[0]*16//meter[1];assert all(len(bar)==length and set(bar)<=set('Xx.-') for line in patterns for bar in line),(ref,patterns)
   assert len({len(line) for line in patterns})==1
   row.update(enabled=num in R,reason='' if num in R else DEFER[num],patterns=patterns,roles=list(R.get(num,())),static_harmony=num in (5,26))
   rhythms.append(row)
  else:
   notes=[list(map(int,v)) for v in re.findall(r'[A-G][b#]?\d@([0-9]+)\+([0-9]+)',body.split('· MIDI')[0])]
   pitches=list(map(int,re.search(r'· MIDI ([0-9 ]+)',body)[1].split()));assert len(notes)==len(pitches)
   notes=[dict(at=a,length=l,pitch=p) for (a,l),p in zip(notes,pitches)]
   steps=int(re.search(r'= (\d+) Schritte',body)[1]);assert all(0<=n['pitch']<=127 and n['length']>0 and n['at']+n['length']<=steps for n in notes)
   assert all(a['at']+a['length']<=b['at'] for a,b in zip(notes,notes[1:]))
   blocked=num in (5,6,9,18,25,26)
   assert 2<=len(notes)<=10 and (blocked or len(notes)<=8)
   assert steps%(meter[0]*16//meter[1])==0
   row.update(enabled=not blocked,reason=('More than eight original notes' if num in (18,25) else 'Original tone set has no exact chord-tone realization in the Barry harmony pool' if num==9 else 'Chromatic non-chord path needs explicit resolution/pedal semantics') if blocked else '',steps=steps,notes=notes)
   motifs.append(row)
 assert len(rhythms)==25 and {r['id'] for r in rhythms}=={'JB-R'+str(i).zfill(2) for i in range(1,28) if i not in (16,23)}
 assert len(motifs)==26 and {m['id'] for m in motifs}=={'JB-M'+str(i).zfill(2) for i in range(1,27)}
 return dict(schema_version=1,rhythms=rhythms,motifs=motifs)
def outputs():
 d=read();h='// Generated by scripts/build_barry_vocabulary.py from canonical research.\n#pragma once\nnamespace stromscore::composition::barry {\n'
 h+='struct RhythmSource {int id,num,den,bars;float x,y,z;bool staticHarmony;const char* bass;const char* movement;};\ninline constexpr RhythmSource rhythms[]={\n'
 for r in d['rhythms']:
  if not r['enabled']:continue
  p={role:''.join(line) for role,line in zip(r['roles'],r['patterns'])};bars=len(r['patterns'][0]);num=int(r['id'][-2:]);x,y,z=r['xyz']
  h+='{'+f'{num},{r["meter"][0]},{r["meter"][1]},{bars},{x}f,{y}f,{z}f,'+str(r['static_harmony']).lower()+','+json.dumps(p.get('bass',''))+','+json.dumps(p.get('movement',''))+'},\n'
 h+='};\nstruct MotifSource {int id,num,den,steps,count;float x,y,z;int pitches[8],at[8],lengths[8];};\ninline constexpr MotifSource motifs[]={\n'
 for m in d['motifs']:
  if not m['enabled']:continue
  h+='{'+f'{int(m["id"][-2:])},{m["meter"][0]},{m["meter"][1]},{m["steps"]},{len(m["notes"])},'+','.join(str(x)+'f' for x in m['xyz'])+','
  h+=','.join('{'+','.join(str(n[k]) for n in m['notes'])+'}' for k in ('pitch','at','length'))+'},\n'
 h+='};\n}\n'
 return {'data/barry/vocabulary.json':json.dumps(d,ensure_ascii=False,indent=2)+'\n','Source/BarryVocabulary.generated.h':h}
def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
 for name,text in outputs().items():
  path=ROOT/name
  if a.check:
   if not path.exists() or path.read_text(encoding="utf-8")!=text:raise ValueError('stale Barry data: '+name)
  else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text,encoding="utf-8")
 print('Canonical Barry R/M data valid and '+('up to date' if a.check else 'generated'))
if __name__=='__main__':main()
